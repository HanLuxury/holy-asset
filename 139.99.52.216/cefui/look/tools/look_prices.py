#!/usr/bin/env python3
"""Price tiers of the look catalog for the gamemode (V159, toko baju dengan harga per item).

    python3 look_prices.py ../LookCatalog.gen.cpp <gamemode>/SERVER/player/look/look_prices.inc

One letter per item, from the item's type (its group name), the same lists and order as LookCatalog.gen.cpp and
look_catalog.inc (items travel as their index):
    a  biasa            b  sweater / jaket      c  merek LV         d  merek Versace
    z  seragam polisi / dinas (gratis, hanya baju & aksesoris model polisi)
The gamemode turns a letter into a price: slot price x tier percent (look_system.inc, scriptfiles override).
Only the standard library is needed.
"""
import re
import sys

KINDS = ['', 'Male', 'Female', 'MalePolice', 'FemalePolice']
SLOTS = ['Hair', 'Beard', 'Makeup', 'Eyebrow', 'Shirt', 'Pants', 'Shoes', 'Hat', 'Glasses', 'Mask', 'Necklace',
         'Watch', 'Earring', 'Bag', 'Vest', 'Belt', 'TatArmL', 'TatArmR', 'TatShoulderL', 'TatShoulderR', 'TatChest',
         'TatBack', 'TatLegL', 'TatLegR']
POLICE = {'MalePolice', 'FemalePolice'}


CLOTHES = set(SLOTS[4:16])   # Shirt .. Belt: the uniform pieces of the police kinds are free


def tier(kind, group, slot=''):
    if kind in POLICE and slot in CLOTHES:
        return 'z'
    g = group.lower()
    if 'versace' in g:
        return 'd'
    if re.search(r'(^|\s)lv($|\s)', g):
        return 'c'
    if 'sweater' in g or 'jaket' in g:
        return 'b'
    return 'a'


def strings(body):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', body)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = open(sys.argv[1], encoding='utf-8').read()
    rows = []
    total = 0
    # The arrays each kind's slots use (police kinds share hair, face and tattoos with the civil kinds).
    cat = src[src.index('const CatalogKind kCatalog[kKinds]'):]
    entries = re.findall(r'\{(k\w+|nullptr), (\d+), (k\w+|nullptr), (\d+), (?:true|false), \w+, \w+\}', cat)
    if len(entries) != (len(KINDS) - 1) * len(SLOTS):
        sys.exit('look_prices: %d slot entries in kCatalog, expected %d' % (len(entries), (len(KINDS) - 1) * len(SLOTS)))
    for k, kind in enumerate(KINDS):
        for si, slot in enumerate(SLOTS):
            if not kind:
                rows.append('')
                continue
            arr, count, garr, _ = entries[(k - 1) * len(SLOTS) + si]
            if arr == 'nullptr':
                rows.append('')
                continue
            m = re.search(r'const CatalogItem %s\[\] = \{(.*?)\n\};' % re.escape(arr), src, re.S)
            gm = re.search(r'const char\* const %s\[\] = \{(.*?)\};' % re.escape(garr), src, re.S) if garr != 'nullptr' else None
            groups = strings(gm.group(1)) if gm else []
            letters = []
            for item in re.finditer(r'\{"(?:[^"\\]|\\.)*", "(?:[^"\\]|\\.)*", (\d+), (\d+), (\d+), 0x[0-9A-Fa-f]+u\}',
                                    m.group(1)):
                group = int(item.group(2))
                letters.append(tier(kind, groups[group] if group < len(groups) else '', slot))
            if len(letters) != int(count):
                sys.exit('look_prices: %s %s: %d items, kCatalog says %s' % (kind, slot, len(letters), count))
            rows.append(''.join(letters))
            total += len(letters)
    out = ['/* Generated by look/tools/look_prices.py (client JNI) from LookCatalog.gen.cpp: do not edit.',
           '   Harga tiap item = harga slot x persen tier (look_system.inc, bisa diubah admin: /lookprice).',
           '   Satu huruf per item, urutan sama dengan look_catalog.inc / client:',
           '   a biasa, b sweater/jaket, c merek LV, d merek Versace, z seragam (gratis).',
           '   Indeks baris: kind * LOOK_SLOTS + slot. */',
           '#if defined _eagle_look_prices',
           '    #endinput',
           '#endif',
           '#define _eagle_look_prices',
           '',
           'stock const gLookTier[LOOK_KINDS * LOOK_SLOTS][] = {']
    for i, r in enumerate(rows):
        out.append('    "%s"%s' % (r, ',' if i + 1 < len(rows) else ''))
    out.append('};')
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('look_prices: %d item, %d baris' % (total, len(rows)))


if __name__ == '__main__':
    main()
